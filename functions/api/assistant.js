export async function onRequestPost(context) {
  const { request, env } = context;
  if (!env.DEEPSEEK_API_KEY) return json({ error: 'not_configured' }, 503);

  const ip = request.headers.get('CF-Connecting-IP') || 'unknown';
  if (rateLimited(ip)) return json({ error: 'rate' }, 429);

  const auth = request.headers.get('Authorization') || '';
  const token = auth.startsWith('Bearer ') ? auth.slice(7).trim() : '';
  if (!token) return json({ error: 'auth' }, 401);

  let body;
  try { body = await request.json(); } catch (e) { return json({ error: 'bad_request' }, 400); }
  const message = String((body && body.message) || '').trim();
  if (!message || message.length > MAX_MESSAGE) return json({ error: 'bad_request' }, 400);
  const ctx = (body.context && typeof body.context === 'object') ? body.context : {};
  const lang = body.lang === 'fa' || body.lang === 'en' ? body.lang : '';
  const prompt = userTurn(message, ctx);
  const ctxSmall = { view: clip(ctx.view, 30) || 'home', slug: clip(ctx.slug, 60) || undefined, wrong: !!(ctx.q && ctx.q.question) };

  const begin = await rpc(env, token, 'ai_chat_begin', {
    p_body: message, p_prompt: prompt, p_context: ctxSmall, p_new: !!body.newThread, p_lang: lang,
  });
  if (begin.status === 401) return json({ error: 'auth' }, 401);
  if (begin.status !== 200) return json({ error: 'db' }, 502);
  const b = begin.data || {};
  if (!b.ok) {
    if (b.reason === 'limit') return json({ error: 'limit', used: b.used, limit: b.limit, vip: !!b.vip }, 429);
    if (b.reason === 'auth') return json({ error: 'auth' }, 401);
    return json({ error: 'bad_request' }, 400);
  }

  const messages = [{ role: 'system', content: SYSTEM }, { role: 'system', content: String(b.profile || '') }]
    .concat(Array.isArray(b.history) ? b.history : [])
    .concat([{ role: 'user', content: prompt }]);
  const model = env.DEEPSEEK_MODEL || DS_MODEL;
  const startedAt = new Date();
  const t0 = Date.now();
  const abort = new AbortController();
  const timer = setTimeout(function () { abort.abort(); }, 60000);
  const fail = function () { return rpc(env, token, 'ai_chat_fail', { p_message_id: b.message_id, p_nonce: b.nonce }).catch(function () {}); };

  let ds;
  try {
    ds = await fetch(DS_URL, {
      method: 'POST',
      signal: abort.signal,
      headers: { Authorization: 'Bearer ' + env.DEEPSEEK_API_KEY, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: model,
        messages: messages,
        thinking: { type: 'disabled' },
        stream: true,
        stream_options: { include_usage: true },
        max_tokens: MAX_TOKENS,
        temperature: 0.6,
      }),
    });
  } catch (e) {
    clearTimeout(timer);
    await fail();
    return json({ error: 'upstream' }, 502);
  }
  if (!ds.ok || !ds.body) {
    clearTimeout(timer);
    let detail = '';
    try { detail = (await ds.text()).slice(0, 300); } catch (e) {}
    console.log('assistant: deepseek ' + ds.status + ' ' + detail);
    await fail();
    return json({ error: 'upstream', status: ds.status }, 502);
  }

  const { readable, writable } = new TransformStream();
  const writer = writable.getWriter();
  const enc = new TextEncoder();
  let clientGone = false;
  const send = async function (obj) {
    if (clientGone) return;
    try { await writer.write(enc.encode('data: ' + JSON.stringify(obj) + '\n\n')); } catch (e) { clientGone = true; }
  };

  const pump = (async function () {
    let text = '', usage = null, finish = '', reasoningChars = 0, buf = '';
    const dec = new TextDecoder();
    await send({ type: 'start', remaining: b.remaining, limit: b.limit });
    try {
      const reader = ds.body.getReader();
      for (;;) {
        const r = await reader.read();
        if (r.done) break;
        buf += dec.decode(r.value, { stream: true });
        let nl;
        while ((nl = buf.indexOf('\n')) >= 0) {
          const line = buf.slice(0, nl).trim();
          buf = buf.slice(nl + 1);
          if (!line.startsWith('data:')) continue;
          const data = line.slice(5).trim();
          if (!data || data === '[DONE]') continue;
          let j;
          try { j = JSON.parse(data); } catch (e) { continue; }
          if (j.usage) usage = j.usage;
          const ch = j.choices && j.choices[0];
          if (!ch) continue;
          if (ch.finish_reason) finish = ch.finish_reason;
          const d = ch.delta || {};
          if (d.reasoning_content) reasoningChars += String(d.reasoning_content).length;   // should stay 0 (thinking off)
          if (d.content) { text += d.content; await send({ type: 'delta', t: d.content }); }
        }
      }
    } catch (e) {
      console.log('assistant: stream error ' + (e && e.message));
    }
    clearTimeout(timer);
    if (!text.trim()) {
      await fail();
      await send({ type: 'error', error: 'upstream' });
    } else {
      if (finish === 'length') { text = text.replace(/\s+$/, '') + ' …'; await send({ type: 'delta', t: ' …' }); }
      const u = usageOf(usage, model, startedAt, Date.now() - t0);
      if (reasoningChars && !u.reasoning) u.reasoning = Math.ceil(reasoningChars / 3);
      const saved = await rpc(env, token, 'ai_chat_finish', { p_message_id: b.message_id, p_nonce: b.nonce, p_body: text, p_usage: u })
        .catch(function () { return { status: 0 }; });
      if (!saved || saved.status !== 200 || saved.data !== true) console.log('assistant: finish not saved for ' + b.message_id);
      await send({ type: 'done', remaining: b.remaining, limit: b.limit, cut: finish === 'length' });
    }
    try { await writer.close(); } catch (e) {}
  })();
  if (context.waitUntil) context.waitUntil(pump);

  return new Response(readable, {
    headers: {
      'Content-Type': 'text/event-stream; charset=utf-8',
      'Cache-Control': 'no-store, no-transform',
      'X-Accel-Buffering': 'no',
    },
  });
}

