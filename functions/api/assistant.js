function rateLimited(ip) {
  const now = Date.now();
  const e = rateMap.get(ip);
  if (!e || now > e.reset) { rateMap.set(ip, { count: 1, reset: now + RATE_WIN }); return false; }
  e.count++;
  return e.count > RATE_MAX;
}

function clip(s, n) {
  return String(s == null ? '' : s).replace(/[\u0000-\u0008\u000b-\u001f]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, n);
}

/* The screen block: built only from known fields, in a fixed order, so the same screen always
   gives the same text (it becomes part of the cached prefix of the next request). */
function screenText(c) {
  c = (c && typeof c === 'object') ? c : {};
  const view = clip(c.view, 30) || 'home';
  const lines = [];
  const lvl = clip(c.level, 3).toUpperCase();
  if (view === 'lesson') {
    lines.push('Today\'s lesson "' + clip(c.title, 80) + '"' + (lvl ? ' (' + lvl + ')' : '') +
      (c.tab ? ', tab: ' + clip(c.tab, 20) : '') + '.');
    if (Array.isArray(c.words) && c.words.length) lines.push('Lesson words: ' + c.words.slice(0, 15).map(function (w) { return clip(w, 30); }).join(', ') + '.');
    if (c.grammar) lines.push('Lesson grammar: ' + clip(c.grammar, 80) + '.');
  } else if (view === 'grammar' && c.slug) {
    lines.push('Grammar guide: "' + clip(c.title, 80) + '" (' + clip(c.slug, 60) + ').');
  } else if (view === 'vocab' && c.slug) {
    lines.push('Vocabulary topic: "' + clip(c.title, 80) + '" (' + clip(c.slug, 60) + ').');
  } else {
    lines.push('Screen: ' + view + (c.title ? ' "' + clip(c.title, 80) + '"' : '') + '.');
  }
  const q = c.q;
  if (q && typeof q === 'object' && q.question) {
    lines.push('The learner just answered this ' + (clip(q.kind, 20) || 'quiz') + ' question WRONG:');
    lines.push('Question: ' + clip(q.question, 300));
    if (Array.isArray(q.options) && q.options.length) lines.push('Options: ' + q.options.slice(0, 6).map(function (o) { return clip(o, 120); }).join(' | '));
    lines.push('Their answer: ' + (clip(q.picked, 160) || '(none)'));
    lines.push('Correct answer: ' + clip(q.correct, 160));
    if (q.explanation) lines.push('App\'s explanation: ' + clip(q.explanation, 400));
  }
  return lines.join('\n');
}

function userTurn(message, context) {
  return '[Screen]\n' + screenText(context) + '\n[Learner]\n' + message;
}

function isPeak(d) {
  const day = d.getUTCDay(), h = d.getUTCHours();
  return day >= 1 && day <= 5 && ((h >= 1 && h < 4) || (h >= 6 && h < 10));
}

function usageOf(u, model, startedAt, ms) {
  u = u || {};
  const prompt = Number(u.prompt_tokens) || 0;
  const hit = Number(u.prompt_cache_hit_tokens) || 0;
  const miss = u.prompt_cache_miss_tokens != null ? (Number(u.prompt_cache_miss_tokens) || 0) : Math.max(prompt - hit, 0);
  const out = Number(u.completion_tokens) || 0;
  const reasoning = Number(u.completion_tokens_details && u.completion_tokens_details.reasoning_tokens) || 0;
  const peak = isPeak(startedAt);
  const f = peak ? 1 : 0.5;
  const cost = (hit * PRICE.hit + miss * PRICE.miss + out * PRICE.out) * f / 1e6;
  return { model: model, hit: hit, miss: miss, out: out, reasoning: reasoning, cost_usd: Number(cost.toFixed(8)), peak: peak, ms: ms };
}

async function rpc(env, token, fn, args) {
  const base = env.SUPABASE_URL || SB_URL;
  const anon = env.SUPABASE_ANON_KEY || SB_ANON_FALLBACK;
  const r = await fetch(base + '/rest/v1/rpc/' + fn, {
    method: 'POST',
    headers: { apikey: anon, Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' },
    body: JSON.stringify(args),
  });
  if (r.status === 401 || r.status === 403) return { status: 401 };
  if (!r.ok) return { status: r.status, error: (await r.text()).slice(0, 300) };
  return { status: 200, data: await r.json() };
}

