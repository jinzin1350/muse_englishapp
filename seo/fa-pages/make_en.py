"""Build /en/index.html (the English home) from the root index.html.
Usage: python3 make_en.py /path/to/repo
The landing block between <!-- LANDING:START --> and <!-- LANDING:END --> is
copied, links are pointed at the app on '/', and the dated parts (hero phone
card + "Today's lessons") are refreshed in the browser from '/' so they never
go stale even if nobody rebuilds this file."""
import os, re, sys

REPO = sys.argv[1]
SITE = "https://museenglishapp.com"
src = open(os.path.join(REPO, "index.html"), encoding="utf-8").read()

landing = src.split("<!-- LANDING:START -->", 1)[1].split("<!-- LANDING:END -->", 1)[0]
style = re.search(r"<style>\s*/\* ---- Muse English landing.*?</style>", src, re.S).group(0)
style = style.replace("html.app-mode #landing{display:none!important}\n", "")
# Fix: long topic names pushed the 2-column topic grid past the screen on phones.
style = style.replace("</style>", "#landing .ltopic-card{min-width:0}#landing .ltopic-card b{overflow-wrap:anywhere}"
                      "@media (max-width:640px){#landing .ltopic-grid{grid-template-columns:repeat(2,minmax(0,1fr))}}\n</style>")
main_css = re.search(r'<link rel="stylesheet" href="/css/main\.css\?v=[0-9a-f]+">', src).group(0)
hotjar = re.search(r"<!-- Hotjar Tracking Code.*?</script>", src, re.S).group(0)
title = re.search(r"<title>(.*?)</title>", src).group(1)
desc = re.search(r'<meta name="description" content="([^"]*)">', src).group(1)

# Links: app routes live on '/', Home is /en/.
landing = re.sub(r'href="#/', 'href="/#/', landing)
landing = landing.replace('href="/">Home</a>', 'href="/en/">Home</a>')
landing = re.sub(r'(<a class="lbrand"[^>]*href=)"/"', r'\1"/en/"', landing)
landing = re.sub(r'<a href="/fa/" lang="fa"( hreflang="fa")?>', '<a href="/fa/" lang="fa" hreflang="fa" data-home-lang="fa">', landing)
if 'href="/fa/"' not in landing:
    landing = landing.replace('<li><a href="/about/">About</a></li></ul></div>\n</div>\n<div class="lfoot-base">',
                              '<li><a href="/about/">About</a></li><li><a href="/fa/" lang="fa" hreflang="fa" data-home-lang="fa">فارسی</a></li></ul></div>\n</div>\n<div class="lfoot-base">', 1)

page = f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <meta name="theme-color" content="#FF9600">
  <!-- Generated by seo/fa-pages/make_en.py from the root landing. Rebuild, don't hand-edit. -->
  <title>{title}</title>
  <meta name="description" content="{desc}">
  <link rel="canonical" href="{SITE}/en/">
  <link rel="alternate" hreflang="en" href="{SITE}/en/">
  <link rel="alternate" hreflang="fa" href="{SITE}/fa/">
  <link rel="alternate" hreflang="x-default" href="{SITE}/">
  <meta property="og:type" content="website">
  <meta property="og:title" content="{title}">
  <meta property="og:description" content="{desc}">
  <meta property="og:url" content="{SITE}/en/">
  <meta property="og:image" content="{SITE}/media/landing/mascot-cta.webp">
  <meta property="og:site_name" content="Muse English">
  <meta name="twitter:card" content="summary_large_image">
  <link rel="icon" href="/favicon.ico" sizes="16x16 32x32 48x48">
  <link rel="icon" type="image/png" sizes="32x32" href="/icons/icon-32.png">
  <link rel="apple-touch-icon" href="/icons/apple-touch-icon.png">
  <script type="application/ld+json">{{"@context":"https://schema.org","@type":"WebPage","url":"{SITE}/en/","name":"{title}","inLanguage":"en","isPartOf":{{"@type":"WebSite","@id":"{SITE}/#website","name":"Muse English","url":"{SITE}/"}}}}</script>
  {style}
  {main_css}
  {hotjar}
</head>
<body>
{landing}
<script>
/* Language choice: remember it so a bare '/' opens this home next time. */
document.addEventListener('click', function (e) {{
  var a = e.target.closest && e.target.closest('[data-home-lang]');
  if (a) {{ try {{ localStorage.setItem('muse_home_lang', a.getAttribute('data-home-lang')); }} catch (err) {{}} }}
}});
/* Keep the dated parts fresh: copy today's hero card + "Today's lessons" from '/'. */
(function () {{
  try {{
    fetch('/', {{ cache: 'no-cache' }}).then(function (r) {{ return r.text(); }}).then(function (html) {{
      var doc = new DOMParser().parseFromString(html, 'text/html');
      ['#today', '.lhero-visual'].forEach(function (sel) {{
        var fresh = doc.querySelector('#landing ' + sel), cur = document.querySelector('#landing ' + sel);
        if (fresh && cur) {{
          fresh.querySelectorAll('a[href^="#/"]').forEach(function (a) {{ a.setAttribute('href', '/' + a.getAttribute('href')); }});
          cur.replaceWith(document.importNode(fresh, true));
        }}
      }});
    }}).catch(function () {{}});
  }} catch (e) {{}}
}})();
</script>
</body>
</html>
"""
os.makedirs(os.path.join(REPO, "en"), exist_ok=True)
open(os.path.join(REPO, "en", "index.html"), "w", encoding="utf-8").write(page)
print("wrote en/index.html", len(page))
