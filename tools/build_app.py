#!/usr/bin/env python3
"""Build js/main.js from src/app/*.js and js/staff.js from src/staff/*.js (Claude, 2026-11-12).

js/main.js used to be one 20,000-line file. It is now cut into src/app/NN-name.js at its own
section headers, in the same order. This script puts the pieces back together, byte for byte,
so the browser still gets one file and nothing about how the app runs has changed.

    python3 tools/build_app.py           # write js/main.js + js/staff.js + the ?v= hashes in index.html
    python3 tools/build_app.py --check   # exit 1 if js/main.js or js/staff.js is not exactly the build

js/staff.js (2026-11-12): teacher dashboard, teacher portal (/teachers), admin views and admin panel
(/manage). Learners never download it. js/main.js loads it on first use (src/app/06a-staff-loader.js)
and runs it inside the app's scope. For each name in STAFF_ENTRIES (staff functions that learner-side
code calls: the router, the click handler, init) this script adds a stand-in to js/main.js that loads
js/staff.js and then calls the real function. If learner-side code must call another staff function,
add its name to STAFF_ENTRIES. Code that learners need must stay in src/app/.

Rules:
- Edit src/app/*.js, never js/main.js. Then run this script and commit both.
- Files are joined in file-name order (00-…, 01-…). The pieces are not standalone modules;
  they share one IIFE that opens in 00-core.js and closes at the end of 28-wordmap.js.
- APP_VERSION comes from version.json. Bump version.json, then build.
- Owned by Claude, don't edit: 05-fa-ui-engine.js, 08-preview.js, and the Persian
  parts of 14-grammar.js (see CLAUDE_PERSIAN_WORK.md).
"""
import glob, hashlib, json, os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, 'src', 'app')
STAFF_SRC = os.path.join(REPO, 'src', 'staff')
OUT = os.path.join(REPO, 'js', 'main.js')
STAFF_OUT = os.path.join(REPO, 'js', 'staff.js')
STAFF_HEADER = ('/* GENERATED by tools/build_app.py from src/staff/*.js. Do not edit this file. Loaded on demand '
                'by js/main.js (src/app/06a-staff-loader.js) and run inside the app scope. */\n')
# Staff functions that learner-side code (router, click handler, init) calls. Each gets a stand-in in js/main.js.
STAFF_ENTRIES = [
    'renderAdmin', 'renderAdminTeacherView', 'renderTeacher', 'renderPlanner', 'renderTeachers', 'renderAdminPanel',
    'copyTeacherLink', 'openTeacherStudent', 'teacherSetLevel', 'teacherIssueCert', 'teacherRemoveStudent',
    'teacherRevokeCert', 'teacherNudge', 'toggleTeacherSent', 'teacherMessageComposer', 'teacherAssignmentComposer',
    'twLogout', 'createAssignment', 'savePlanner', 'aiReportTeacherStudent', 'aiReportClass', 'openTeacherAssignment',
    'loadTeacherAssignments', 'cancelScheduledAssignment', 'deleteTeacherAssignment', 'saveAdminBotChat',
    'adminApproveTeacher', 'adminRejectTeacher', 'renderAdminAnalytics', 'openAdminUser', 'setUserLevel',
    'adminAddTeacher', 'teacherMessageSend',
]
HEADER = ('/* GENERATED by tools/build_app.py from src/app/*.js. Do not edit this file: '
          'edit src/app/ and run python3 tools/build_app.py */\n')
HASHED = [('js/main.js', 'main.js'), ('css/main.css', 'main.css'), ('js/fa-ui.js', 'fa-ui.js')]


def read(p):
    with open(p, encoding='utf-8', newline='') as f:
        return f.read()


def staff_text():
    parts = sorted(glob.glob(os.path.join(STAFF_SRC, '*.js')))
    if not parts:
        sys.exit('build_app: no files in src/staff/')
    body = ''.join(read(p) for p in parts)
    for name in STAFF_ENTRIES:
        if not re.search(r'(^|\n)(async )?function ' + re.escape(name) + r'\s*\(', body):
            sys.exit('build_app: STAFF_ENTRIES lists %s but src/staff/ has no function %s' % (name, name))
    export = ('\n/* generated: hand the entry points to js/main.js */\n__staffApi = {\n' +
              ',\n'.join('  %s: %s' % (n, n) for n in STAFF_ENTRIES) + '\n};\n//# sourceURL=/js/staff.js\n')
    return STAFF_HEADER + body.rstrip('\n') + '\n' + export


def build_text():
    parts = sorted(glob.glob(os.path.join(SRC, '*.js')))
    if not parts:
        sys.exit('build_app: no files in src/app/')
    body = ''.join(read(p) for p in parts)
    try:
        v = json.load(open(os.path.join(REPO, 'version.json'), encoding='utf-8'))['v']
        body = re.sub(r"var APP_VERSION = '\d+';", "var APP_VERSION = '%s';" % v, body, count=1)
    except (OSError, KeyError, ValueError):
        pass
    for name in STAFF_ENTRIES:
        if re.search(r'(^|\n)(async )?function ' + re.escape(name) + r'\s*\(', body):
            sys.exit('build_app: %s is in STAFF_ENTRIES but also defined in src/app/' % name)
    stubs = ('\n/* ---------------- generated by tools/build_app.py: stand-ins for staff code (js/staff.js) ---------------- */\n' +
             ''.join("function %s() { return callStaff('%s', this, arguments); }\n" % (n, n) for n in STAFF_ENTRIES))
    cut = body.rfind('})();')
    if cut < 0:
        sys.exit('build_app: could not find the end of the app IIFE in src/app/')
    body = body[:cut] + stubs.lstrip('\n') + '\n' + body[cut:]
    staff_v = hashlib.sha1(staff_text().encode('utf-8')).hexdigest()[:8]
    body = body.replace('__STAFF_JS_V__', staff_v)
    return HEADER + body


def file_hash(rel):
    with open(os.path.join(REPO, rel), 'rb') as f:
        return hashlib.sha1(f.read()).hexdigest()[:8]


def lazy_landing_images(h):
    """The old English landing inside index.html (<!-- LANDING:START/END -->) is hidden in the app
    (html.app-mode #landing {display:none}), but its <img> tags without loading="lazy" were still
    downloaded on every app open (~300 KB). Lazy images inside a hidden block are never fetched."""
    a, b = h.find('<!-- LANDING:START -->'), h.find('<!-- LANDING:END -->')
    if a < 0 or b < a:
        return h
    block = h[a:b]
    block = re.sub(r'<img\b(?![^>]*\bloading=)', '<img loading="lazy"', block)
    block = re.sub(r'(<img\b[^>]*\bloading=)"eager"', r'\1"lazy"', block)
    return h[:a] + block + h[b:]


def fix_hashes():
    """Point the ?v= cache-busters in index.html at the current file contents, and keep the hidden
    landing's images lazy (see lazy_landing_images)."""
    p = os.path.join(REPO, 'index.html')
    h = read(p)
    new = lazy_landing_images(h)
    for rel, name in HASHED:
        if os.path.exists(os.path.join(REPO, rel)):
            new = re.sub(re.escape(name) + r'\?v=[0-9a-f]+', name + '?v=' + file_hash(rel), new)
    if new != h:
        with open(p, 'w', encoding='utf-8', newline='') as f:
            f.write(new)
        return True
    return False


def main():
    outs = [(OUT, build_text(), 'js/main.js', 'src/app'), (STAFF_OUT, staff_text(), 'js/staff.js', 'src/staff')]
    if '--check' in sys.argv:
        bad = [rel for p, text, rel, src in outs if text != (read(p) if os.path.exists(p) else '')]
        if bad:
            print('build_app: %s NOT the build of src/. Someone edited it directly, or forgot to run '
                  'python3 tools/build_app.py.' % ' and '.join(bad))
            sys.exit(1)
        print('build_app: js/main.js and js/staff.js match src/')
        return
    for p, text, rel, src in outs:
        if text != (read(p) if os.path.exists(p) else ''):
            with open(p, 'w', encoding='utf-8', newline='') as f:
                f.write(text)
            print('build_app: wrote %s (%d lines)' % (rel, text.count('\n')))
        else:
            print('build_app: %s already up to date' % rel)
    if fix_hashes():
        print('build_app: updated ?v= hashes in index.html')


if __name__ == '__main__':
    main()
